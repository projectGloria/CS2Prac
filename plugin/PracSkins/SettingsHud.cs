            SetGodFor(p, on);
    }

    private void SetGodFor(CCSPlayerController player, bool on)
    {
        if (!player.IsValid || player.PlayerPawn.Value is not { IsValid: true } pawn) return;
        // the agent preview keeps the pawn invulnerable while it runs and restores it itself
        if (_hudSessions.TryGetValue(player.Slot, out var hs) && hs.View != null) return;
        pawn.TakesDamage = !on;
    }

    private void ClearFlash(CCSPlayerController player)
    {
        void Clear()
        {
            if (!player.IsValid || player.PlayerPawn.Value is not { IsValid: true } pawn) return;
            pawn.FlashDuration = 0f;
            pawn.FlashMaxAlpha = 0f;
            Utilities.SetStateChanged(pawn, "CCSPlayerPawnBase", "m_flFlashDuration");
            Utilities.SetStateChanged(pawn, "CCSPlayerPawnBase", "m_flFlashMaxAlpha");
        }
        Clear();
        Server.NextFrame(Clear);
    }

    /// <summary>
    /// Sky: the picked material (precached at map load) is written straight into the map's own env_sky entities
    /// (m_hSkyMaterial + m_hSkyMaterialLightingOnly, network change callback SkyStateChanged), like
    /// samyycX/CS2-SkyboxChanger. A new env_sky of ours never drew on the client: on maps with a 3D skybox (Mirage)
    /// the sky has to live in the skybox's spawn group, and disabling the map's sky only left it black or unchanged.
    /// "" writes the map's own material pointers back.
    /// </summary>
    private void ApplySky(string material)
    {
        RemoveOurSky();
        _sky = "";
        if (material.Length == 0) return;
        if (Skies.All(s => s.Material != material)) return; // only precached materials
        var ptr = FindMaterial(material);
        if (ptr == 0)
        {
            Logger.LogWarningSafe($"sky: material {material} not found (FindOrCreateMaterialFromResource)");
            return;
        }
        foreach (var sky in Utilities.FindAllEntitiesByDesignerName<CEnvSky>("env_sky").Where(e => e.IsValid))
        {
            _skyOriginals[sky] = (Marshal.ReadIntPtr(sky.SkyMaterial.Handle), Marshal.ReadIntPtr(sky.SkyMaterialLightingOnly.Handle));
            WriteSkyMaterial(sky, ptr, ptr);
        }
        _sky = material;
    }

    private readonly Dictionary<CEnvSky, (IntPtr Sky, IntPtr Lighting)> _skyOriginals = new();

    private static void WriteSkyMaterial(CEnvSky sky, IntPtr skyMat, IntPtr lightingMat)
    {
        Marshal.WriteIntPtr(sky.SkyMaterial.Handle, skyMat);
        Marshal.WriteIntPtr(sky.SkyMaterialLightingOnly.Handle, lightingMat);
        Utilities.SetStateChanged(sky, "CEnvSky", "m_hSkyMaterial");
        Utilities.SetStateChanged(sky, "CEnvSky", "m_hSkyMaterialLightingOnly");
    }

    private delegate IntPtr FindOrCreateMaterialDelegate(IntPtr materialSystem, IntPtr outMaterial, [MarshalAs(UnmanagedType.LPStr)] string name);

    /// <summary>VMaterialSystem2_001's FindOrCreateMaterialFromResource (vtable index 14, Windows), as CS2-SkyboxChanger.
    /// Returns the material handle (InfoForResourceTypeIMaterial2*) that m_hSkyMaterial holds, 0 when unknown.</summary>
    private IntPtr FindMaterial(string path)
    {
        try
        {
            if (path.EndsWith("_c")) path = path[..^2];
            var system = NativeAPI.GetValveInterface(0, "VMaterialSystem2_001");
            if (system == 0) return 0;
            var fn = Marshal.ReadIntPtr(Marshal.ReadIntPtr(system) + 14 * IntPtr.Size);
            var find = Marshal.GetDelegateForFunctionPointer<FindOrCreateMaterialDelegate>(fn);
            var slot = Marshal.AllocHGlobal(IntPtr.Size);
            try
            {
                Marshal.WriteIntPtr(slot, 0);
                var result = find(system, slot, path);
                return result == 0 ? 0 : Marshal.ReadIntPtr(result);
            }
            finally
            {
                Marshal.FreeHGlobal(slot);
            }
        }
        catch (Exception e)
        {
            Logger.LogWarningSafe($"sky: FindMaterial failed: {e.Message}");
            return 0;
        }
    }

    private void RemoveOurSky()
    {
        foreach (var (sky, orig) in _skyOriginals)
            if (sky.IsValid) WriteSkyMaterial(sky, orig.Sky, orig.Lighting);
        _skyOriginals.Clear();
    }

