    /// <summary>Start names: lowercase letters, digits, - and _ (SpotName). End names also take capitals and spaces.</summary>
    private static readonly string[] KeyRows = ["abcdef", "ghijkl", "mnopqr", "stuvwx", "yz-_", "123456", "7890"];
