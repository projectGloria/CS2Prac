    // css_pracmenu is the one to bind: MatchZy registers css_settings too and prints its "Current Settings" on it.
    [ConsoleCommand("css_pracmenu", "Open or close the CS2Prac server settings window (bind a key: bind l css_pracmenu)")]
    [CommandHelper(whoCanExecute: CommandUsage.CLIENT_ONLY)]
    public void OnPracMenuCommand(CCSPlayerController? player, CommandInfo command)
    {
        if (player == null) return;
        var arg = command.GetArg(1).ToLowerInvariant();
        // Not in the command handler: the first window of a server takes ~0.3 s (the HUD API's one-time type lookup),
        // and the engine drops a client whose string commands take that long in one go ("ProcessMessages has
        // exhausted its CPU time budget", then NETWORK_DISCONNECT_OVERFLOW; user pressed L a few times).
        Server.NextFrame(() =>
        {
            if (player is not { IsValid: true }) return;
            if (arg == "close")
            {
                CloseSettings(player);
                CloseHud(player);
                return;
            }
            if (arg == "open" && _setSessions.ContainsKey(player.Slot)) return;
            ToggleSettings(player, null);
        });
    }

