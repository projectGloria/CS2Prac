    /// <summary>
    /// Rename opens an on-screen keyboard inside the Spots tab (Panorama's custom HUD allows no text field): the
    /// window stays open, letters are chips (KeyRows), Save applies. A chat line or !name &lt;text&gt; while it is
    /// open saves that text at once (TakeRename).
    /// </summary>
    private void StartRename(SetSession s, int index, bool end)
    {
        if (index < 0 || index >= _moveSpots.Count) return;
        var spot = _moveSpots[index];
        s.Rename = new SpotRename { Index = index, End = end, Spot = spot.Name, Text = end ? spot.EndName ?? "" : spot.Name };
        SetStatus(s, "Click the letters, then Save");
    }

    private void BuildRenameRows(SetSession s, SpotRename r)
    {
        var max = r.End ? EndNameMax : StartNameMax;
        void Type(string ch)
        {
            if (r.Text.Length >= max) { SetStatus(s, $"Names are at most {max} characters"); return; }
            r.Text += ch;
            SetStatus(s, r.Text);
        }
        var shown = r.Text.Length == 0 ? (r.End ? $"(empty = {r.Spot} end)" : "(empty)") : r.Text + "_";
        var top = new List<(string Label, bool Picked, Action<CCSPlayerController> Click)>
        {
            ("Save", false, pl => FinishRename(pl, s, r)),
            ("Cancel", false, _ => { s.Rename = null; SetStatus(s, "Name kept"); }),
            ("Back", false, _ => { if (r.Text.Length > 0) r.Text = r.Text[..^1]; SetStatus(s, r.Text); }),
            ("Clear", false, _ => { r.Text = ""; SetStatus(s, "Cleared"); })
        };
        if (r.End)
        {
            top.Add(("Shift", r.Upper, _ => { r.Upper = !r.Upper; SetStatus(s, r.Upper ? "Capitals" : "Small letters"); }));
            top.Add(("Space", false, _ => Type(" ")));
        }
        s.Rows.Add(new SetRow(shown, r.End ? $"New name for the end point of {r.Spot}" : $"New name for {r.Spot} (lowercase, one word)", top) { Icon = "ic-edit" });
        foreach (var keys in KeyRows)
            s.Rows.Add(new SetRow("", "", keys.Select(k =>
            {
                var ch = r.Upper && char.IsLetter(k) ? char.ToUpperInvariant(k).ToString() : k.ToString();
                return (ch, false, (Action<CCSPlayerController>)(_ => Type(ch)));
            }).ToList()) { Icon = "ic-edit" });
    }

    private void FinishRename(CCSPlayerController player, SetSession s, SpotRename r)
    {
        LoadMoveSpots();
        var index = _moveSpots.FindIndex(sp => sp.Name == r.Spot); // the list may have changed meanwhile
        var error = index < 0 ? "that spot is gone" : r.End ? RenameEnd(index, r.Text) : RenameStart(index, r.Text);
        error = error?.TrimEnd('.');
        Logger.LogInformation("rename: {Spot} {Which} -> \"{Text}\": {Result}", r.Spot, r.End ? "end" : "start", r.Text, error ?? "ok");
        if (error != null) { SetStatus(s, "Not renamed: " + error); return; }
        s.Rename = null;
        SetStatus(s, r.End ? $"End point renamed to {(r.Text.Trim().Length == 0 ? r.Spot + " end" : r.Text.Trim())}" : $"Renamed to {_moveSpots[index].Name}");
    }

    /// <summary>A chat line (or !name &lt;text&gt;) while the rename keyboard is open: saved as the name at once.</summary>
    private bool TakeRename(CCSPlayerController player, string text)
    {
        if (!_setSessions.TryGetValue(player.Slot, out var s) || s.Rename is not { } r) return false;
        text = text.Trim().Trim('"').Trim();
        // an empty line or a command (.settings, !name …) is not a name; !name ends up here with its text
        if (text.Length == 0 || text[0] is '.' or '!' or '/') return false;
        Server.NextFrame(() =>
        {
            if (!player.IsValid || !_setSessions.TryGetValue(player.Slot, out var now) || now.Rename != r) return;
            r.Text = text;
            FinishRename(player, now, r);
            BuildSettings(player, now);
            RenderSettings(player, now);
        });
        return true;
    }

