// Bundled by build-site.mjs (vite SSR build, `electron` aliased to electron-stub.ts) and run in Node: downloads the
// ByMykel skin data (falls back to the snapshot in resources/bundle/catalog), builds the same catalog the app uses
// and writes the item site's data file and the Markdown docs in docs/items.
import { existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { gunzipSync } from 'node:zlib'
import { buildCatalog } from '../../src/main/skins/catalog'
import { itemInfo, metaLine, wearSpan, WEAPON_STATS, weaponStatRows } from '../../src/shared/itemInfo'
import type { Catalog } from '../../src/shared/skins'

const API = 'https://raw.githubusercontent.com/ByMykel/CSGO-API/main/public/api/en/'
const FILES = ['skins.json', 'base_weapons.json', 'agents.json', 'stickers.json', 'keychains.json', 'collectibles.json', 'music_kits.json', 'graffiti.json']

async function load(root: string, file: string): Promise<unknown[]> {
  try {
    const res = await fetch(API + file)
    if (res.ok) return (await res.json()) as unknown[]
    console.warn(`${file}: HTTP ${res.status}`)
  } catch (e) {
    console.warn(`${file}: ${(e as Error).message}`)
  }
  const snap = join(root, 'resources', 'bundle', 'catalog', file + '.gz')
  if (existsSync(snap)) return JSON.parse(gunzipSync(readFileSync(snap)).toString('utf8'))
  console.warn(`${file}: no snapshot either, left empty`)
  return []
}

export async function loadCatalog(root: string): Promise<Catalog> {
  const [skins, base, agents, stickers, keychains, collectibles, musicKits, graffiti] = await Promise.all(FILES.map((f) => load(root, f)))
  // eslint-disable-next-line @typescript-eslint/no-explicit-any
  const any = (x: unknown[]) => x as any
  return buildCatalog(any(skins), any(base), Date.now(), {
    agents: any(agents),
    stickers: any(stickers),
    keychains: any(keychains),
    collectibles: any(collectibles),
    musicKits: any(musicKits),
    graffiti: any(graffiti)
  })
}

const SITE = 'https://projectgloria.github.io/CS2Prac/'
const esc = (s: string) => s.replace(/\|/g, '\\|').replace(/\r?\n/g, ' ')
const slug = (s: string) => s.toLowerCase().replace(/★/g, '').replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '')
const plainName = (s: string) => s.replace(/^★\s*/, '')

function table(head: string[], rows: string[][]): string {
  return [`| ${head.join(' | ')} |`, `| ${head.map(() => '---').join(' | ')} |`, ...rows.map((r) => `| ${r.map(esc).join(' | ')} |`)].join('\n')
}

/** docs/items: an index, a stats table, one page per weapon (finishes) and one per other item kind */
export function writeDocs(c: Catalog, dir: string): number {
  rmSync(dir, { recursive: true, force: true })
  mkdirSync(join(dir, 'weapons'), { recursive: true })
  const header = (title: string) =>
    `<!-- generated by npm run build:docs (scripts/site); do not edit -->\n# ${title}\n\nData: ByMykel/CSGO-API skin data and the game's weapons.vdata, ${new Date(c.fetchedAt).toISOString().slice(0, 10)}. Searchable with pictures: [the item site](${SITE}).\n\n`
  let pages = 0
  const put = (file: string, text: string) => {
    writeFileSync(join(dir, file), text)
    pages++
  }

  const stats = c.weapons
    .filter((w) => WEAPON_STATS[w.className] && w.kind === 'weapon')
    .map((w) => {
      const s = WEAPON_STATS[w.className]
      return [`[${plainName(w.name)}](weapons/${slug(w.name)}.md)`, w.category, `$${s.price}`, `$${s.killAward}`, s.bullets > 1 ? `${s.damage}×${s.bullets}` : String(s.damage), String(s.rpm), `${s.clip}/${s.reserve}`, `${s.armorPen}%`, String(s.speed)]
    })
  put('weapon-stats.md', header('Weapon stats') + table(['Weapon', 'Category', 'Price', 'Kill award', 'Damage', 'RPM', 'Magazine', 'Armor pen', 'Speed'], stats) + '\n')

  const byDef = new Map<number, typeof c.skins>()
  for (const s of c.skins) (byDef.get(s.defIndex) ?? byDef.set(s.defIndex, []).get(s.defIndex)!).push(s)
  const weaponLinks: string[] = []
  for (const w of c.weapons) {
    const skins = byDef.get(w.defIndex) ?? []
    const info = itemInfo(c, { kind: 'weapon', def: w.defIndex })
    const rows = weaponStatRows(w.className)
    let text = header(plainName(w.name))
    text += `${w.category} · \`${w.className}\` · def index ${w.defIndex} · ${skins.length} finishes\n\n`
    if (rows.length) text += table(['Stat', 'Value'], rows.map((r) => [r.label, r.value])) + '\n\n'
    text += '## Finishes\n\n'
    text += table(
      ['Finish', 'Rarity / collection', 'Wear', 'Paint kit', 'StatTrak'],
      skins.map((s) => [s.name, metaLine(s.meta) || '–', `${s.minFloat.toFixed(2)}–${s.maxFloat.toFixed(2)} (${wearSpan(s.minFloat, s.maxFloat)})`, String(s.paintKit), s.stattrak ? 'yes' : 'no'])
    )
    put(join('weapons', `${slug(w.name)}.md`), text + '\n')
    if (info) weaponLinks.push(`- [${plainName(w.name)}](weapons/${slug(w.name)}.md) (${skins.length})`)
  }

  const simple = (file: string, title: string, items: { name: string; defIndex: number; meta?: { rarity?: string; collections?: string[]; crates?: string[] } }[], extra?: (i: never) => string) => {
    put(
      file,
      header(title) +
        table(
          ['Name', 'Def', 'Rarity', 'Collection / found in', ...(extra ? ['More'] : [])],
          items.map((i) => [i.name, String(i.defIndex), i.meta?.rarity ?? '–', i.meta?.collections?.[0] ?? i.meta?.crates?.[0] ?? '–', ...(extra ? [extra(i as never)] : [])])
        ) +
        '\n'
    )
  }
  simple('agents.md', 'Agents', c.agents, (a: { team: string }) => (a.team === 't' ? 'T' : 'CT'))
  simple('pins.md', 'Pins, coins and medals', c.pins, (p: { type: string }) => p.type)
  simple('music-kits.md', 'Music kits', c.musicKits)
  simple('graffiti.md', 'Graffiti', c.graffiti)
  simple('charms.md', 'Charms', c.keychains)
  const events = new Map<string, number>()
  for (const s of c.stickers) events.set(s.event || s.type || 'Other', (events.get(s.event || s.type || 'Other') ?? 0) + 1)
  put(
    'stickers.md',
    header('Stickers') +
      `${c.stickers.length} stickers. The full list with pictures is on [the item site](${SITE}#stickers); by event or type:\n\n` +
      table(['Event / type', 'Stickers'], [...events].sort((a, b) => b[1] - a[1]).map(([e, n]) => [e, String(n)])) +
      '\n'
  )

  put(
    'README.md',
    header('CS2Prac item docs') +
      'What every item the K window and the Loadout tab offer is: rarity, collection, wear range and weapon stats. ' +
      'In game, `!info` prints the same for the item in your hand; in the app, right-click a tile (or its (i) button).\n\n' +
      `- [Weapon stats](weapon-stats.md)\n- [Agents](agents.md) (${c.agents.length})\n- [Stickers](stickers.md) (${c.stickers.length})\n- [Charms](charms.md) (${c.keychains.length})\n` +
      `- [Pins](pins.md) (${c.pins.length})\n- [Music kits](music-kits.md) (${c.musicKits.length})\n- [Graffiti](graffiti.md) (${c.graffiti.length})\n\n## Weapons, knives and gloves\n\n` +
      weaponLinks.join('\n') +
      '\n'
  )
  return pages
}

export async function main(root: string, siteDir: string | null, docsDir: string | null): Promise<void> {
  const c = await loadCatalog(root)
  console.log(`catalog: ${c.weapons.length} weapons, ${c.skins.length} skins, ${c.stickers.length} stickers`)
  if (siteDir) {
    mkdirSync(join(siteDir, 'data'), { recursive: true })
    writeFileSync(join(siteDir, 'data', 'catalog.json'), JSON.stringify(c))
    console.log(`site data -> ${join(siteDir, 'data', 'catalog.json')}`)
  }
  if (docsDir) console.log(`docs: ${writeDocs(c, docsDir)} pages -> ${docsDir}`)
}
